const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const zlib = require('zlib');

// Wraps the webpack bundle into the firmware-served dash: the bundle is
// substituted into index.html's %%%SCRIPT%%% marker, the result is
// gzipped and emitted as the DASH[] PROGMEM array in dash.cpp/dash.h.
//
// Exported for the unit test (dash/src/__tests__/wrap.test.js); run as a
// script via the Makefile's `dash` target it wraps the default files.

// A fingerprint of the bundle's *inputs*: the dash sources, the page that
// wraps them, and the lockfile that pins the webpack/babel/terser chain.
// Embedded into the generated files so a freshness check can compare it
// against a freshly computed one - a byte-exact diff of the gzip payload
// would not work across environments, because webpack's minimized output
// is not byte-stable across node versions (the committed blob reproduces
// only under the node major that last regenerated it).
function inputHash(dashDir) {
  const hash = crypto.createHash('sha256');
  const roots = ['src', 'index.html', 'package-lock.json'];
  const files = [];
  for (const root of roots) {
    const full = path.join(dashDir, root);
    if (fs.statSync(full).isFile()) {
      files.push(full);
      continue;
    }
    const walk = (dir) => {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name.startsWith('.') || entry.name === '__tests__')
          continue;
        const child = path.join(dir, entry.name);
        if (entry.isDirectory())
          walk(child);
        else
          files.push(child);
      }
    };
    walk(full);
  }
  // Sorted paths, content-relative separators: the same tree must hash the
  // same on every platform.
  for (const file of files.sort()) {
    hash.update(path.relative(dashDir, file).replace(/\\/g, '/'));
    hash.update('\0');
    hash.update(fs.readFileSync(file));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function wrap({ htmlPath, scriptPath, headerPath, codePath, dashDir = null }) {
  const html = fs.readFileSync(htmlPath, 'utf8');
  const script = fs.readFileSync(scriptPath, 'utf8');
  // The replacer must be a function: the bundle may contain '$&' and other
  // special replacement patterns that String.replace would otherwise expand.
  const combined = html.replace('%%%SCRIPT%%%', () => script);
  const combinedCompressed = zlib.gzipSync(Buffer.from(combined, 'utf8'));

  const length = combinedCompressed.length;
  const bytesNum = Array.from(combinedCompressed).join(', ');

  const hashLine = dashDir
    ? `// Inputs sha256: ${inputHash(dashDir)}\n`
    : '';
  const generatedComment = `// Generated by dash/wrap.js - do not edit.\n${hashLine}`;

  const headerContent = generatedComment + `#include <Arduino.h>\n\nextern const uint8_t DASH[${length}];`;
  fs.writeFileSync(headerPath, headerContent, 'utf8');

  const codeContent = generatedComment + `#include "dash.h"\n\nconst uint8_t DASH[${length}] PROGMEM = { ${bytesNum} };`;
  fs.writeFileSync(codePath, codeContent, 'utf8');

  return { length, combined, combinedCompressed };
}

if (require.main === module) {
  if (process.argv[2] === '--check') {
    // Freshness check (CI): the committed src/dash.{h,cpp} must carry the
    // inputs hash of the *current* tree. A mismatch means the dash sources
    // or the lockfile changed without regenerating (`make dash`) - or the
    // blob was regenerated from different sources than committed.
    const header = fs.readFileSync(path.join('..', 'src', 'dash.h'), 'utf8');
    const embedded = header.match(/^\/\/ Inputs sha256: ([0-9a-f]{64})$/m);
    if (!embedded) {
      console.error('src/dash.h carries no inputs hash - regenerate with `make dash`.');
      process.exit(1);
    }
    const current = inputHash('.');
    if (embedded[1] !== current) {
      console.error(`src/dash.h is stale: embedded ${embedded[1]}, current ${current}.`);
      console.error('Regenerate with `make dash` and commit the output.');
      process.exit(1);
    }
    console.log('src/dash.h inputs hash matches the tree.');
  } else {
    wrap({
      htmlPath: 'index.html',
      scriptPath: 'bundle.js',
      headerPath: 'dash.h',
      codePath: 'dash.cpp',
      dashDir: '.',
    });
  }
}

module.exports = { wrap, inputHash };